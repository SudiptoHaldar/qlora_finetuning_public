"""The cost record for reading and for the repository (req_005 v5.02).

``cost.build_record`` works the figures out; this module shows them. ``render_markdown``
turns a record into the Markdown copy, and ``write_record`` writes both files under the
comparison's report folder, only when every check passed. A record with a reservation is
written with "provisional" in its title.

Usage::

    from qlora_finetuning.comparison.cost_report import usd, write_record

    markdown_path, json_path = write_record(record, cfg, report_dir)
    usd("0.047202")        # "$0.047"; two decimals from one dollar up, three below

This module imports neither boto3 nor the training stack.
"""

from __future__ import annotations

from decimal import Decimal
from pathlib import Path
from typing import Any

from qlora_finetuning.comparison.cost import COMMAND, DEVELOPMENT, SELECT, TEST, TRAIN
from qlora_finetuning.comparison.cost_config import CostConfig
from qlora_finetuning.comparison.cost_scenarios import ALWAYS_ON, BATCH, MAKING
from qlora_finetuning.comparison.gate import canonical_json
from qlora_finetuning.settings import ConfigError
from qlora_finetuning.tracking.config import check_no_secrets


def usd(text: Any) -> str:
    """An amount for reading: two decimals from one dollar up, three below."""
    if text is None:
        return "—"
    amount = Decimal(str(text))
    return f"${amount:,.2f}" if abs(amount) >= 1 or amount == 0 else f"${amount:.3f}"


def _whole(text: Any) -> str:
    return f"{Decimal(str(text)).to_integral_value():,}"


def _cell(text: Any) -> str:
    return str(text).replace("|", "\\|")


def break_even_text(entry: dict[str, Any]) -> str:
    if entry["kind"] == "equal":
        return "the same at every volume"
    if entry["kind"] == "always":
        return f"{entry['cheaper_always']} is cheaper at every volume"
    return (
        f"{entry['questions']:,} questions: below it {entry['cheaper_below']} is cheaper, "
        f"above it {entry['cheaper_above']}"
    )


SCENARIO_NAMES = {
    ALWAYS_ON: "always-on endpoint, a month",
    BATCH: "batch job, a month",
    MAKING: "with the cost of making the model",
}


def render_markdown(record: dict[str, Any]) -> str:
    title = "# The cost model" + (" (provisional)" if record["provisional"] else "")
    prices = record["prices"]
    lines = [
        title,
        "",
        f"Generated by `{COMMAND} report`. Do not edit by hand.",
        "",
        "What each arm cost and what it would cost to use (req_005 v5.02). Every figure is a",
        "quantity from the ledger times a price from `config/pricing.yaml`, except an amount",
        "marked billed, which the owner read from the AWS bill. Figures are at list price:",
        "AWS bills by service and day, not by run. This file holds no example text.",
        "",
        f"- Runs priced through {record['through']}",
        f"- Bedrock price list published {prices['bedrock']['published']}; SageMaker training "
        f"{prices['sagemaker']['training_published']}, hosting "
        f"{prices['sagemaker']['hosting_published']}",
    ]
    if record["provisional"]:
        lines.append("- **Provisional**: a check passed with a reservation; see the checks below")
    lines += ["", "## Checks", "", "| Id | Check | Result | Detail |", "|---|---|---|---|"]
    for check in record["checks"]:
        result = "PASS" if check["passed"] else "FAIL"
        if check["reservation"]:
            result = "PASS, with a reservation"
        lines.append(f"| {check['id']} | {check['name']} | {result} | {_cell(check['detail'])} |")

    lines += [
        "",
        "## Making each tuned model",
        "",
        "The one training run that made the model. For A1 the scoring job that chose its",
        "checkpoint is shown beside it. A tuned Nova model also costs a fixed amount a month",
        "for as long as it is kept.",
        "",
        "| Arm | Training run | Basis | Selection | Together | Storage a month |",
        "|---|---:|---|---:|---:|---:|",
    ]
    for arm, entry in record["making"].items():
        train, select, storage = entry["train"], entry["select"], entry["storage"]
        lines.append(
            f"| {arm} | {usd(train['usd']) if train else '—'} | "
            f"{train['basis'] if train else ''} | {usd(select['usd']) if select else '—'} | "
            f"{usd(entry['making_usd'])} | {usd(storage['per_month']) if storage else '—'} |"
        )
    kept = {arm: e["storage"] for arm, e in record["making"].items() if e["storage"]}
    if kept:
        months = sorted(next(iter(kept.values()))["months"], key=int)
        lines += ["", "Keeping a tuned Nova model:", ""]
        lines.append(
            "| Arm | " + " | ".join(f"{m} month" + ("" if m == "1" else "s") for m in months) + " |"
        )
        lines.append("|---|" + "---:|" * len(months))
        for arm, storage in kept.items():
            lines.append(
                f"| {arm} | " + " | ".join(usd(storage["months"][m]) for m in months) + " |"
            )

    lines += [
        "",
        "## The test pass",
        "",
        f"Each arm answered the {record['test_examples']:,} test questions once."
        if record["test_examples"]
        else "",
        "For a Qwen arm, *as run* is the job's billable seconds, start-up included, and",
        "*steady* is the run's own seconds inside the job: what a longer job approaches.",
        "",
        "| Arm | Quantity | Test pass | Per 1,000 questions | Steady | Correct "
        "| Per 1,000 correct answers |",
        "|---|---|---:|---:|---:|---:|---:|",
    ]
    for arm, figure in record["test_pass"].items():
        if "billable_seconds" in figure:
            quantity = f"{figure['billable_seconds']:,} billable seconds, {figure['instance_type']}"
        else:
            quantity = f"{figure['input_tokens']:,} tokens in, {figure['output_tokens']:,} out"
        lines.append(
            f"| {arm} | {quantity} | {usd(figure['usd'])} | {usd(figure['per_1000_questions'])} | "
            f"{usd(figure.get('per_1000_questions_steady'))} | {figure['correct']:,} | "
            f"{usd(figure['per_1000_correct'])} |"
        )

    assumptions = record["serving_assumptions"]
    lines += [
        "",
        "## Serving Qwen",
        "",
        "Computed from the test job's throughput on one instance at batch size 8; no endpoint",
        "was created. An endpoint that answers one request at a time is slower, so its real",
        "cost per question is higher than the always-on figures below.",
    ]
    for arm, scenario in record["serving"].items():
        lines += [
            "",
            f"### {arm}",
            "",
            f"- {Decimal(scenario['seconds_per_question']):.3f} seconds a question: about "
            f"{_whole(scenario['questions_per_hour'])} questions an hour, "
            f"{_whole(scenario['questions_per_month'])} in a month of "
            f"{assumptions['hours_per_month']} hours",
            f"- A job's start-up: {_whole(scenario['startup_seconds'])} seconds, "
            f"{usd(scenario['startup_usd'])}",
            "",
            "| Batch job of | Cost | Per 1,000 questions |",
            "|---:|---:|---:|",
        ]
        for row in scenario["batch"]:
            lines.append(
                f"| {row['questions']:,} questions | {usd(row['usd'])} | "
                f"{usd(row['per_1000_questions'])} |"
            )
        always = scenario["always_on"]
        if always:
            lines += [
                "",
                f"An always-on endpoint: ${Decimal(always['hourly_usd']):.3f} an hour, "
                f"{usd(always['monthly_usd'])} a month, whatever the load.",
                "",
                "| Utilization | Questions a month | Per 1,000 questions |",
                "|---:|---:|---:|",
            ]
            for row in always["at"]:
                lines.append(
                    f"| {Decimal(row['utilization']) * 100:.0f}% | "
                    f"{_whole(row['questions_per_month'])} | {usd(row['per_1000_questions'])} |"
                )

    count = assumptions["batch_jobs_per_month"]
    jobs = "one job" if count == 1 else f"{count} jobs"
    lines += [
        "",
        "## Break-evens",
        "",
        "The volume at which two arms cost the same. A month's cost is a fixed amount plus a",
        "cost per question: for an always-on endpoint the fixed amount is the instance; for a",
        f"batch job it is the start-up of {jobs} a month; for",
        "a tuned Nova model it is storage. *With the cost of making the model* compares the",
        "training cost and the steady cost per question, with no monthly amounts.",
        "",
        "| Pair | Scenario | Break-even | Reachable here | Why |",
        "|---|---|---|---|---|",
    ]
    for entry in record["break_evens"]:
        lines.append(
            f"| {entry['pair'][0]} and {entry['pair'][1]} | {SCENARIO_NAMES[entry['scenario']]} | "
            f"{break_even_text(entry)} | {'yes' if entry['reachable'] else '**no**'} | "
            f"{_cell(entry['limit_note'])} |"
        )
    limits = ", ".join(
        f"{arm} {limit}" for arm, limit in assumptions["requests_per_minute"].items()
    )
    lines += [
        "",
        f"The account's limits, in requests a minute (read {assumptions['limits_read_on']}): "
        f"{limits}.",
    ]

    project = record["project"]
    lines += [
        "",
        "## The project so far",
        "",
        "Every effective ledger record, in one category. *Development* is everything that was",
        "not a model's training run, its selection, or a test pass: smoke jobs, runs on dev",
        "and quick-dev, trials, failed runs. Runs on the owner's machine have no AWS charge.",
        "",
        "| Path | Train | Select | Test | Development | Total | Cap |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for path, row in project["paths"].items():
        lines.append(
            f"| {path} | {usd(row[TRAIN])} | {usd(row[SELECT])} | {usd(row[TEST])} | "
            f"{usd(row[DEVELOPMENT])} | {usd(row['total'])} | {usd(row['cap'])} |"
        )
    if project["storage_so_far"]:
        stored = ", ".join(f"{arm} {usd(v)}" for arm, v in project["storage_so_far"].items())
        lines += ["", f"Storage of the tuned Nova models so far, not in the table: {stored}."]

    lines += [
        "",
        "## Against the bill",
        "",
        "The service's total as the owner read it from the AWS bill, beside the model's total",
        "for the same days. For Bedrock the model's total includes storage.",
        "",
        "| Service | Through | Billed | The model | Difference | Agrees |",
        "|---|---|---:|---:|---:|---|",
    ]
    for service in record["reconciliation"]:
        if not service["entries"]:
            lines.append(
                f"| {service['service']} | {service['last_run_date']} | not entered | "
                f"{usd(service['model_usd_to_date'])} | | |"
            )
        for entry in service["entries"]:
            lines.append(
                f"| {service['service']} | {entry['through']} | {usd(entry['billed_usd'])} | "
                f"{usd(entry['model_usd'])} | {usd(entry['difference_usd'])} | "
                f"{'yes' if entry['agrees'] else '**no**'} |"
            )
        if service["entries"] and not service["covered"]:
            lines.append(
                f"| {service['service']} | {service['last_run_date']} | not entered | "
                f"{usd(service['model_usd_to_date'])} | | |"
            )

    lines += ["", "## What is an estimate, and what is left out", ""]
    lines += [f"- Estimate: {text}" for text in record["estimates"]] or [
        "- No priced figure is an estimate: every quantity is AWS's own count or a billed amount."
    ]
    lines += [f"- Left out of the model: {item}" for item in record["left_out"]]
    return "\n".join(lines) + "\n"


def report_paths(cfg: CostConfig, report_dir: Path) -> tuple[Path, Path]:
    return Path(report_dir) / f"{cfg.report_stem}.md", Path(report_dir) / f"{cfg.report_stem}.json"


def write_record(record: dict[str, Any], cfg: CostConfig, report_dir: Path) -> tuple[Path, Path]:
    """Write the cost record and its Markdown copy. Refused unless every check passed."""
    if not record.get("passed"):
        raise ConfigError("the cost record is written only when K1 to K8 pass")
    check_no_secrets(record, cfg.report_stem)
    markdown_path, json_path = report_paths(cfg, report_dir)
    Path(report_dir).mkdir(parents=True, exist_ok=True)
    json_path.write_text(canonical_json(record), encoding="utf-8", newline="\n")
    markdown_path.write_text(render_markdown(record), encoding="utf-8", newline="\n")
    return markdown_path, json_path
